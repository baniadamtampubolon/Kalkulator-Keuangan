export function getKabkotByProvinsi(provinsiName: string): string[] {
  if (!provinsiName) return [];
  const clean = provinsiName.trim().toUpperCase();
  
  if (PROVINSI_KABKOT_MAP[clean]) {
    return PROVINSI_KABKOT_MAP[clean];
  }
  
  // Fuzzy match if needed
  for (const [prov, list] of Object.entries(PROVINSI_KABKOT_MAP)) {
    if (clean.includes(prov) || prov.includes(clean)) {
      return list;
    }
  }
  return ["Kota Lainnya", "Kabupaten Lainnya"];
}
